import assert from "node:assert/strict";
import { Agent, Graph, Random, World } from "city-library";
const ref = Agent.add({ value: 1 });
const alias = { values: [1] };
const cyclic: { self?: unknown; alias: typeof alias } = { alias }; cyclic.self = cyclic;
const bytes = new Uint8Array([1, 2]);
const state = { alias, again: alias, cyclic, map: new Map([[alias, cyclic]]), set: new Set([alias, ref]), bytes, view: new DataView(bytes.buffer), ref };
const graph = Graph.add<{ name: string }, typeof state>({ edgeState: state });
const a = graph.nodes.add({ name: "a" }), b = graph.nodes.add({ name: "b" }), c = graph.nodes.add({ name: "c" });
const ab = graph.edges.add({ from: a, to: b }), bc = graph.edges.add({ from: b, to: c });
assert.equal(ab.alias, ab.again); assert.equal(ab.cyclic.self, ab.cyclic);
assert.equal(ab.cyclic.alias, ab.alias); assert.equal(ab.map.get(ab.alias), ab.cyclic);
assert.equal(ab.set.has(ab.alias), true); assert.equal(ab.set.has(ref), true);
assert.equal(ab.ref, ref); assert.notEqual(ab.alias, bc.alias);
assert.equal(ab.bytes.buffer, ab.view.buffer); assert.notEqual(ab.bytes.buffer, bytes.buffer);
let getterCalls = 0;
const accessor = Object.defineProperty({}, "bad", { get() { getterCalls++; return 1; } });
assert.throws(() => Graph.add({ edgeState: accessor }), TypeError); assert.equal(getterCalls, 0);
for (const node of graph.nodes) {
  assert.throws(() => graph.nodes.delete(node), Error);
  assert.equal(graph.hasNode(node), true);
}
const parallel = Graph.add<object>({ parallel: true, selfLoops: true });
parallel.nodes.add(a); parallel.nodes.add(b);
parallel.edges.add({ from: a, to: b, key: "7" });
parallel.edges.add({ from: b, to: a, directed: true, key: "0" });
assert.equal(parallel.edges.add({ from: a, to: a }).key, "1");
const opposite = Graph.add<object>(); opposite.nodes.add(a); opposite.nodes.add(b);
opposite.edges.add({ from: a, to: b, directed: true }); opposite.edges.add({ from: b, to: a, directed: true });
assert.equal(opposite.edges.size, 2);
assert.equal([...opposite.edges][0]!.path, undefined);
const rng = Random.add({ seed: 211 }), world = World.add({ x: 20, y: 20 }, { random: rng });
world.add(ref);
const owner = Graph.add<typeof ref>(); owner.nodes.add(ref);
const other = Graph.add<typeof ref>(); other.nodes.add(ref);
const before = rng.state; owner.delete();
assert.equal(ref.alive, true); assert.equal(other.hasNode(ref), true); assert.equal(world.agents.length, 1);
ref.delete(); assert.equal(other.hasNode(ref), false); assert.equal(world.agents.length, 0);
assert.deepEqual(rng.state, before); assert.equal(world.tick.value, 0);
console.log(JSON.stringify({ status: "PASS", scope: "Existing public clone primitives, keys, opposite arcs, guards and Agent lifecycle; Graph.copy is not invoked", graphCopyPresent: "copy" in graph, assertions: "source behavior only" }));
