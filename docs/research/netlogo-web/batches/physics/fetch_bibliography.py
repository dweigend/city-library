def fetch(k,q):
 path=E/('publication-'+k+'.json')
 if path.exists(): return k,json.load(open(path))
 try:
  if q.startswith('10.'): url='https://api.crossref.org/works/'+urllib.parse.quote(q,safe='/')
  else: url='https://api.crossref.org/works?query='+urllib.parse.quote(q)+'&rows=3'
  req=urllib.request.Request(url,headers={'User-Agent':'Mozilla/5.0'})
  r=json.load(urllib.request.urlopen(req,timeout=45))['message']; items=r.get('items',[r]);
  d={'query':q,'consultedUrl':url,'checkedAt':'2026-11-05','items':items}
  path.write_text(json.dumps(d,indent=2)+'\n'); return k,d
 except Exception as e:return k,{'error':str(e)}
