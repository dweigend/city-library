import assert from "node:assert/strict";
import { create as brain } from "../../../models/brians-brain/model.ts";
import { create as cyclic } from "../../../models/cyclic-ca/model.ts";
import { create as stochastic } from "../../../models/ca-stochastic/model.ts";
const b = brain({ width: 5, height: 5, initialization: "blank" });
b.setCells(b.read().cells.map(c => c.y === 0 && Math.abs(c.x) === 1 ? 1 : 0));
b.advance();
assert.equal(b.read().cells.find(c => c.x === 0 && c.y === 0)!.state, 1);
assert.equal(b.read().cells.find(c => c.x === 1 && c.y === 0)!.state, 2);
b.advance();
assert.equal(b.read().cells.find(c => c.x === 1 && c.y === 0)!.state, 0);
const y = cyclic({ width: 5, height: 5, preset: "custom", numStates: 3, radius: 1, threshold: 1, neighborhood: "Moore" });
y.setCells(y.read().cells.map(c => c.x === 1 && c.y === 0 ? 1 : 0));
y.advance();
assert.equal(y.read().cells.find(c => c.x === 0 && c.y === 0)!.state, 1);
assert.equal(y.read().cells.find(c => c.x === 1 && c.y === 0)!.state, 1);
const s = stochastic({ width: 9, height: 5, density: 0, OOO: 100, seed: 2 });
s.advance();
assert.equal(s.read().cells.filter(c => c.y === 1 && c.on).length, 9);
assert.equal(s.read().probabilities.reduce((a,b) => a+b, 0), 1);
const z = stochastic({ width: 9, height: 5, density: 0, OOO: 0, autoContinue: true });
z.advance(20);
assert.equal(z.read().tick, 4); // absorbing bottom row stops without a tick
