import assert from "node:assert/strict";
import { create as vants } from "../../../models/vants/model.ts";
import { create as turing } from "../../../models/turing-machine-2d/model.ts";
const v = vants({ width: 9, height: 9, vantCount: 2, seed: 7 });
const initial = v.read();
v.advance(25);
v.reverse(25);
assert.equal(v.read().tick, 50);
assert.deepEqual(v.read().cells.map(c => c.on), initial.cells.map(c => c.on));
assert.deepEqual(v.read().agents.map(a => [a.x, a.y, a.heading]), initial.agents.map(a => [a.x, a.y, a.heading]));
const t = turing({ width: 9, height: 9, heads: 1, seed: 1 });
t.setRules([[1, 90, true], [0, 0, false], [0, 0, false], [0, 0, false]]);
t.advance();
assert.equal(t.read().tick, 1);
assert.equal(t.read().agents[0]!.state, 1);
assert.equal(t.read().agents[0]!.heading, 90);
assert.equal(t.read().agents[0]!.x, 1);
assert.equal(t.read().agents[0]!.y, 0);
assert.equal(t.read().cells.filter(c => c.on).length, 1);
