import assert from "node:assert/strict";
import { Agent, Store } from "city-library";

const depot = Store.add<string>({ capacity: 1 });
const first = depot.put("bread");
const second = depot.put("vegetables");
const third = depot.put("medicine");
assert.equal(first.status, "stored");
assert.equal(second.status, "waiting");
assert.deepEqual(depot.items, ["bread"]);
assert.equal(depot.take(), "bread");
assert.equal(second.status, "stored");
assert.equal(third.status, "waiting");
assert.deepEqual(depot.items, ["vegetables"]);
depot.cancelPut(third);
assert.equal(third.status, "cancelled");
assert.equal(depot.get().value, "vegetables");
const waitingConsumer = depot.get();
assert.equal(waitingConsumer.status, "waiting");
const laterConsumer = depot.get();
depot.put("water");
assert.equal(waitingConsumer.status, "received");
assert.equal(waitingConsumer.value, "water");
assert.equal(laterConsumer.status, "waiting");
assert.deepEqual(depot.items, []);
depot.cancelGet(laterConsumer);
assert.equal(laterConsumer.status, "cancelled");
assert.equal(depot.waitingGets.length, 0);
assert.equal(depot.waitingPuts.length, 0);

const rider = Agent.add({ cargo: 1 });
const shelter = Store.add<typeof rider>({ capacity: 1 });
shelter.put(rider);
assert.throws(() => rider.delete());
assert.equal(shelter.take(), rider);
rider.delete();
assert.throws(() => shelter.put(rider));
assert.throws(() => Store.add({ capacity: 0 }));
console.log("DES bounded producer/consumer FIFO, cancellation and canonical store identity passed");
