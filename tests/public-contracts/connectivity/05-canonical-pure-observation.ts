import assert from "node:assert/strict";
import { Agent, Graph, Random, World } from "city-library";
const random=Random.create({seed:42}),world=World.create({random});
const a=world.add(Agent.create({energy:4})),b=world.add(Agent.create({energy:8}));
const graph=Graph.create<typeof a>();
graph.nodes.add(a);graph.nodes.add(b);
const edge=graph.edges.add({from:a,to:b});
const state=random.state;
const captured=graph.components();
assert.equal(captured[0]![0],a);
a.energy=5;
assert.equal(captured[0]![0]!.energy,5);
for(let i=0;i<10;i++)assert.equal(graph.isConnected(),true);
assert.deepEqual(random.state,state);
assert.equal(world.tick.value,0);
edge.delete();
assert.deepEqual(graph.components(),[[a],[b]]);
assert.deepEqual(captured,[[a,b]]);
b.delete();
assert.deepEqual(graph.components(),[[a]]);
assert.equal(world.agents.length,1);
