import assert from "node:assert/strict";
import { create as ants } from "../../../models/ants/model.ts";
import { create as bugs } from "../../../models/heatbugs/model.ts";
const colony = ants({ population: 2, seed: 9 });
const setup = colony.read();
assert.equal(setup.ants.length, 2);
assert.ok(setup.ants.every(a => a.x === 0 && a.y === 0));
colony.advance();
assert.ok(colony.read().ants.every(a => a.x === 0 && a.y === 0)); // who >= ticks stops locally
colony.advance();
assert.equal(colony.read().tick, 2);
assert.ok(colony.read().ants.some(a => a.x !== 0 || a.y !== 0));
assert.deepEqual(colony.read().foodByPile, setup.foodByPile);
const heat = bugs({ bugCount: 10, seed: 5 });
assert.ok(heat.read().cells.every(c => c.temp === 0));
heat.heatUp();
assert.ok(heat.read().cells.every(c => c.temp === 25));
heat.deepFreeze();
assert.ok(heat.read().cells.every(c => c.temp === 0));
heat.advance();
const state = heat.read();
assert.equal(state.tick, 1);
assert.equal(new Set(state.bugs.map(b => `${b.x},${b.y}`)).size, 10);
assert.ok(Math.abs(state.cells.reduce((s, c) => s + c.temp, 0) - state.bugs.reduce((s, b) => s + b.outputHeat, 0)) < 1e-9);
console.log("Delayed departure, heat interventions, unique occupancy and emission balance verified.");
