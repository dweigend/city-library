import assert from "node:assert/strict";
import { Graph } from "../../../index.ts";
const graph = Graph.add<object, { weight: number }>({ edgeState: { weight: 2 } });
const a = graph.nodes.add({}), b = graph.nodes.add({});
const edge = graph.edges.add({ from: a, to: b, directed: true });
let calls = 0;
assert.throws(() => graph.distances({ from: {}, cost: () => { calls++; return 1; } }), TypeError);
assert.throws(() => graph.distances({ from: a, algorithm: "breadth", cost: () => { calls++; return 1; } }), TypeError);
assert.equal(calls, 0);
assert.throws(() => graph.distances({ from: a, cost: () => NaN }), TypeError);
assert.throws(() => graph.distances({ from: a, cost: () => Promise.resolve(1) as unknown as number }), TypeError);
const sentinel = new Error("caller error");
assert.throws(() => graph.distances({ from: a, cost: () => { throw sentinel; } }), error => error === sentinel);
assert.throws(() => graph.distances({ from: a, cost: () => { graph.nodes.add({}); return 1; } }));
assert.equal(graph.nodes.size, 2); assert.equal(graph.edges.size, 1);
const order: unknown[] = [];
graph.allDistances({ cost: current => { order.push(current); return current.weight; } });
assert.deepEqual(order, [edge]); // Once per edge for the entire top-level all-pairs query.
const before = graph.distances({ from: a, cost: current => current.weight });
edge.weight = 9;
assert.equal(before.get(b), 2);
assert.equal(graph.distances({ from: a, cost: current => current.weight }).get(b), 9);
