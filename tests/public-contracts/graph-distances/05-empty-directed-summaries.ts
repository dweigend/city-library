import assert from "node:assert/strict";
import { Graph } from "../../../index.ts";
const graph = Graph.create<{ id: string }>();
const empty = graph.distanceSummary();
assert.equal(empty.mean, undefined); assert.equal(empty.radius, undefined); assert.equal(empty.diameter, undefined);
assert.equal(empty.eccentricity.size, 0); assert.equal(empty.reachablePairs, 0);
assert.equal(graph.allDistances().size, 0);
const a = graph.nodes.add({ id: "a" });
const singleton = graph.distanceSummary();
assert.equal(singleton.mean, undefined); assert.equal(singleton.radius, 0); assert.equal(singleton.diameter, 0);
assert.equal(singleton.eccentricity.get(a), 0);
const b = graph.nodes.add({ id: "b" }), c = graph.nodes.add({ id: "c" });
graph.edges.add({ from: a, to: b, directed: true });
graph.edges.add({ from: b, to: c, directed: true });
const summary = graph.distanceSummary();
assert.equal(summary.reachablePairs, 3);
assert.equal(summary.mean, 4 / 3); assert.equal(summary.diameter, 2); assert.equal(summary.radius, 0);
assert.equal(summary.eccentricity.get(a), 2); assert.equal(summary.eccentricity.get(b), 1); assert.equal(summary.eccentricity.get(c), 0);
assert.throws(() => graph.distanceSummary({ disconnected: "reject" }), RangeError);
let calls = 0;
const weighted = graph.distanceSummary({ cost: () => { calls++; return 0; } });
assert.equal(calls, 2); assert.equal(weighted.mean, 0); assert.equal(weighted.diameter, 0);
assert.equal(graph.allDistances().get(c)!.has(a), false);
