import assert from "node:assert/strict";
import { create } from "../../../models/des-elevator/model.ts";

const elevator = create({ floorCount: 3, elevatorCount: 1, capacity: 1, travelTimeSeconds: 1, doorTimeSeconds: 1, transferTimeSeconds: 1, initialPassengerCount: 0 });
assert.equal(elevator.addPassenger(0, 2), 1);
assert.equal(elevator.read().tick, 0);
assert.equal(elevator.read().waitingPassengerCount, 1);
elevator.advance(2);
assert.equal(elevator.read().passengers[0]!.boarded, 2);
assert.equal(elevator.read().ridingPassengerCount, 1);
assert.equal(elevator.read().cars[0]!.used, 1);
elevator.advance(5);
const delivered = elevator.read();
assert.equal(delivered.passengers[0]!.arrived, 7);
assert.equal(delivered.arrivedPassengerCount, 1);
assert.equal(delivered.waitingPassengerCount + delivered.ridingPassengerCount, 0);
assert.equal(delivered.meanWaitSeconds, 2);
assert.equal(delivered.meanRideSeconds, 5);
assert.equal(delivered.meanSystemSeconds, 7);
elevator.advance();
assert.equal(elevator.read().cars[0]!.status, "idle");
assert.equal(elevator.read().time, 8);
assert.equal(elevator.read().tick, 8);
