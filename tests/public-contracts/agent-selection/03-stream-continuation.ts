import assert from "node:assert/strict";
import { Random, World } from "city-library";

const random = Random.create({ seed: 42 });
const world = World.create({ random });
random.number();
const saved = random.state;
assert.ok(Object.isFrozen(saved));
assert.ok(Object.isFrozen(saved.continuation));
const copy = random.copy();
assert.notEqual(copy, random);
assert.deepEqual(copy.state, saved);
const expected = [copy.number(), copy.number(), copy.number()];
assert.deepEqual([random.number(), random.number(), random.number()], expected);
random.state = saved;
assert.equal(world.random, random);
assert.deepEqual([world.random.number(), world.random.number(), world.random.number()], expected);
assert.equal(world.tick.value, 0);
random.reseed(-1);
assert.equal(random.seed, 0xffffffff);
assert.equal(random.state.continuation.gaussian, null);
assert.equal(random.number(), Random.create({ seed: -1 }).number());
random.state = { ...saved, continuation: { ...saved.continuation, gaussian: 0.75 } };
assert.equal(random.copy().state.continuation.gaussian, 0.75);
random.reseed(42);
assert.equal(random.state.continuation.gaussian, null);
random.state = saved;
assert.equal(random.seed, 42);
assert.equal(saved.seed, 42);
assert.equal(saved.continuation.gaussian, null);
assert.equal(random.number(), expected[0]);
console.log("stream-continuation: independent copies, in-place restore, explicit reseed");
