import assert from "node:assert/strict";
import { Agent, Grid, World } from "city-library";
const world=World.add({x:5,y:5});
const grid=world.add(Grid.add({x:5,y:5}));
const a=world.add(Agent.add({energy:4}));
const cell=grid.fieldAt(a)!;
const old=grid.agentsAt(cell);
const b=a.copy();
assert.deepEqual(grid.agentsAt(cell),[a]);
world.add(b);
assert.deepEqual(grid.agentsAt(cell),[a,b]);
b.energy=9;
assert.equal((grid.agentsAt(cell)[1] as typeof b).energy,9);
a.delete();
assert.deepEqual(grid.agentsAt(cell),[b]);
assert.deepEqual(old,[a]);
assert.equal(old[0]!.alive,false);
assert.ok(Object.isFrozen(old));
world.delete(b);
assert.equal(b.alive,true);
assert.deepEqual(grid.agentsAt(cell),[]);
