import assert from "node:assert/strict";
import { Agent, Grid, World } from "city-library";
const world=World.create();
const grid=world.add(Grid.create({x:4,y:4,boundary:"wrap"}));
const a=world.add(Agent.create({}, {position:{x:2,y:0}}));
const b=Agent.create({}, {position:{x:-2,y:0}});
const cell=grid.fieldAt(a)!;
assert.deepEqual(grid.agentsAt(cell),[a]);
assert.deepEqual(grid.agentsAt(cell,{source:[b,a,b]}),[b,a]);
const xyz=world.add(Agent.create({}, {position:{x:0,y:0,z:0}}));
assert.throws(()=>grid.agentsAt(cell));
assert.deepEqual(grid.agentsAt(cell,{source:[a]}),[a]);
xyz.delete();
assert.deepEqual(grid.agentsAt(cell),[a]);
a.move({to:{x:6,y:0}});
assert.deepEqual(grid.agentsAt(cell),[a]);
const hard=world.add(Grid.create({x:4,y:4}));
assert.deepEqual(hard.agentsAt(hard.fields[0]!),[]);
