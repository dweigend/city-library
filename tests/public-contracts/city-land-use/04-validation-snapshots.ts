import assert from "node:assert/strict";
import { model } from "../../../models/city-land-use/model.ts";

assert.throws(() => model.create({ residentialDemand: 40, commercialDemand: 9 }), RangeError);
for (const value of [-1, 0.5, NaN, Infinity, 49]) assert.throws(() => model.create({ residentialDemand: value }), RangeError);
assert.throws(() => model.create({ growthPattern: "sprawl" as never }), RangeError);
const first = model.create();
const second = model.create();
const before = first.read();
for (const steps of [-1, 0.5, NaN, Infinity, 1_000_001]) assert.throws(() => first.advance(steps), RangeError);
assert.throws(() => first.setDemand({ residentialDemand: 43 }), RangeError);
assert.throws(() => first.setDemand({ commercialDemand: NaN }), RangeError);
assert.throws(() => first.setDemand({ residentialDemand: 10, commercialDemand: undefined }), TypeError);
assert.throws(() => first.setDemand({ conversionLimit: 3 } as never), TypeError);
assert.throws(() => first.setGrowthPattern(undefined as never), TypeError);
assert.throws(() => first.setGrowthPattern("leapfrog" as never), RangeError);
assert.throws(() => first.applyProtectionPlan("ring" as never), RangeError);
assert.throws(() => first.applyProtectionPlan(undefined as never), TypeError);
assert.throws(() => first.setProtection("parcel:48", true), RangeError);
assert.throws(() => first.setProtection("parcel:0", "yes" as unknown as boolean), TypeError);
assert.deepEqual(first.read(), before);
assert.ok(Object.isFrozen(before.parcels[0]));
assert.ok(Object.isFrozen(before.parameters));
first.advance(0);
assert.deepEqual(first.read(), before);
first.advance(3);
second.advance(); second.read(); second.advance(2);
assert.deepEqual(first.read(), second.read());
assert.equal(before.tick, 0);
assert.equal(before.parcels[6]?.use, "green");
first.setDemand({ residentialDemand: 4 });
assert.equal(second.read().parameters.residentialDemand, 24);
assert.equal(first.read().parameters.commercialDemand, 6);
console.log("city-land-use validation and snapshots passed");
