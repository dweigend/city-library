import assert from "node:assert/strict";
import { model } from "../../../models/des-emergency-dispatch/model.ts";

const dispatch = model.create();
const independent = model.create();
assert.equal(dispatch.read().busyResponderCount, 1);
assert.equal(dispatch.read().waitingCallCount, 2);
assert.deepEqual(dispatch.read(), dispatch.read());
dispatch.advance(4);
assert.deepEqual(dispatch.read().order, [1]);
assert.equal(dispatch.read().calls[1]!.started, 4);
assert.equal(dispatch.read().calls[2]!.started, -1);
dispatch.advance(14);
assert.deepEqual(dispatch.read().order, [1, 2, 3]);
assert.deepEqual(dispatch.read().calls.map((call) => call.completed), [4, 12, 18]);
assert.equal(dispatch.read().busyResponderCount, 0);
assert.equal(dispatch.read().waitingCallCount, 0);
assert.equal(independent.read().time, 0);
const expanded = model.create();
expanded.setResponders(3);
expanded.advance(8);
assert.equal(expanded.read().completedCallCount, 3);
assert.deepEqual(expanded.read().calls.map((call) => call.completed), [4, 8, 6]);
assert.throws(() => expanded.setResponders(0), RangeError);
assert.equal(expanded.read().parameters.responderCount, 3);
