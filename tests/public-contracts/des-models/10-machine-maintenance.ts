import assert from "node:assert/strict";
import { model } from "../../../models/des-machine-maintenance/model.ts";

const maintenance = model.create();
const independent = model.create();
assert.equal(maintenance.read().operationalMachineCount, 3);
assert.equal(maintenance.read().availability, 1);
maintenance.advance(4);
assert.equal(maintenance.read().operationalMachineCount, 0);
assert.equal(maintenance.read().busyRepairTeamCount, 1);
assert.equal(maintenance.read().waitingMachineCount, 2);
maintenance.advance(6);
assert.equal(maintenance.read().completedRepairCount, 2);
assert.equal(maintenance.read().operationalMachineCount, 1);
assert.equal(maintenance.read().busyRepairTeamCount, 1);
assert.equal(maintenance.read().waitingMachineCount, 1);
assert.deepEqual(maintenance.read().machines.map((machine) => machine.availability), [0.6, 0.5, 0.4]);
assert.equal(maintenance.read().availability, 0.5);
assert.deepEqual(maintenance.read(), maintenance.read());
assert.equal(independent.read().time, 0);
const expanded = model.create();
expanded.advance(4);
expanded.setRepairTeams(3);
expanded.advance(3);
assert.equal(expanded.read().completedRepairCount, 3);
assert.equal(expanded.read().operationalMachineCount, 3);
assert.throws(() => expanded.setRepairTeams(0), RangeError);
assert.equal(expanded.read().parameters.repairTeamCount, 3);
