import assert from "node:assert/strict";
import { Agent, Graph, World } from "city-library";

const first = Agent.add({ label: "First" });
const second = Agent.add({ label: "Second" });
const world = World.add();
world.add([first, second]);
const defaults = { cost: 1, notes: { visits: 0 } };
const graph = Graph.add<typeof first, typeof defaults>({ edgeState: defaults });
defaults.notes.visits = 99;
graph.nodes.add(first);
graph.nodes.add(second);
const edge = graph.edges.add({ from: first, to: second });
assert.equal(edge.notes.visits, 0);
edge.cost = 4;
const supplied = { cost: 8, notes: { visits: 2 } };
assert.equal(graph.edges.add({ from: second, to: first, state: supplied }), edge);
assert.equal(edge.cost, 4);
const holder = Agent.add({ network: graph, connection: edge });
assert.equal(holder.network, graph);
assert.equal(holder.connection, edge);
assert.equal(holder.copy().connection, edge);

world.delete(first);
assert.equal(first.alive, true);
assert.equal(graph.hasNode(first), true);
assert.equal(edge.alive, true);
const other = Graph.add<typeof first>();
other.nodes.add(first);
other.nodes.add(second);
const otherEdge = other.edges.add({ from: first, to: second });
first.delete();
assert.equal(graph.hasNode(first), false);
assert.equal(other.hasNode(first), false);
assert.equal(edge.alive, false);
assert.equal(otherEdge.alive, false);
assert.equal(edge.cost, 4);
assert.equal(edge.from, first);
assert.equal(graph.edges.has(edge), false);
assert.throws(() => graph.nodes.add(first));
assert.throws(() => holder.copy());
edge.delete();
edge.delete();
assert.equal(second.alive, true);
assert.equal(second.world, world);

const third = Agent.add({ label: "Third" });
graph.nodes.add(third);
const replacement = graph.edges.add({ from: second, to: third });
assert.equal(replacement.notes.visits, 0);
replacement.notes.visits = 5;
assert.equal(defaults.notes.visits, 99);
const snapshot = Array.from(graph.nodes);
graph.delete({ edgesOnly: true });
assert.equal(replacement.alive, false);
assert.deepEqual(Array.from(graph.nodes), snapshot);
assert.equal(graph.edges.size, 0);
assert.equal(world.agents.length, 1);
graph.delete();
assert.equal(graph.nodes.size, 0);
assert.equal(second.alive, true);
assert.equal(third.alive, true);
assert.equal(second.world, world);
graph.delete();

const plain = Graph.add<{ name: string }>();
plain.nodes.add({ name: "one" });
assert.throws(() => {
  for (const _node of plain.nodes) plain.nodes.add({ name: "forbidden during iteration" });
});
assert.equal(plain.nodes.size, 1);
plain.nodes.add({ name: "allowed after iteration closes" });
assert.equal(plain.nodes.size, 2);
console.log("graph-lifecycle: independent edge state, shared identities and canonical deletion cleanup");
