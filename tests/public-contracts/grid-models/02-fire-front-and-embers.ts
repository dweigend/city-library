import assert from "node:assert/strict";
import { create } from "../../../models/fire/model.ts";

const fire = create({ width: 5, height: 3, density: 0 });
fire.setForest(fire.read().cells.map(({ x, y }) => y === 0 && (x === -1 || x === 0)));
assert.equal(fire.read().initialTreeCount, 2);
assert.equal(fire.read().burnedTreeCount, 0);
assert.deepEqual(fire.read().counts, { treeCount: 2, fireCount: 3, emberCount: 0 });
fire.advance();
assert.equal(fire.read().tick, 1);
assert.equal(fire.read().burnedTreeCount, 1);
assert.deepEqual(fire.read().counts, { treeCount: 1, fireCount: 1, emberCount: 3 });
fire.advance();
assert.equal(fire.read().burnedTreeCount, 2);
assert.deepEqual(fire.read().counts, { treeCount: 0, fireCount: 1, emberCount: 4 });
fire.advance();
assert.equal(fire.read().done, false);
assert.deepEqual(fire.read().counts, { treeCount: 0, fireCount: 0, emberCount: 5 });
fire.advance(100);
assert.equal(fire.read().tick, 14);
assert.equal(fire.read().done, true);
assert.equal(fire.read().percentBurned, 100);
const stopped = fire.read();
fire.advance();
assert.deepEqual(fire.read(), stopped);
