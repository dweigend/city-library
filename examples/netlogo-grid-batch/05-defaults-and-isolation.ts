import assert from "node:assert/strict";
import { create as createFire } from "../../models/fire/model.ts";
import { create as createLife } from "../../models/life/model.ts";
import { create as createPercolation } from "../../models/percolation/model.ts";

const fire = createFire({ density: 0 });
assert.equal(fire.read().width, 251);
assert.equal(fire.read().height, 251);
assert.deepEqual(fire.read().counts, { trees: 0, fires: 251, embers: 0 });
assert.equal(fire.read().initialTrees, 0);
assert.equal(fire.read().percentBurned, 0);
assert.equal(createFire().read().parameters.density, 57);
const first = createLife();
const second = createLife();
assert.equal(first.read().width, 101);
assert.equal(first.read().height, 101);
assert.equal(first.read().parameters.initialDensity, 35);
assert.equal(first.read().parameters.initialization, "random");
assert.deepEqual(first.read().cells.map(cell => cell.living), second.read().cells.map(cell => cell.living));
const before = second.read();
first.advance();
assert.deepEqual(second.read(), before);
assert.ok(Object.isFrozen(before.cells));
assert.ok(Object.isFrozen(before.cells[0]));
const oil = createPercolation();
assert.equal(oil.read().width, 150);
assert.equal(oil.read().height, 221);
assert.equal(oil.read().parameters.porosity, 60.5);
assert.equal(oil.read().currentRow, 220);
assert.equal(oil.read().counts.front, 75);
assert.equal(oil.read().totalOil, 0);
