import assert from "node:assert/strict";
import { create } from "../../experiments/life/model.ts";

const life = create({ width: 5, height: 5, initialization: "blank" });
const mask = life.read().cells.map(({ x, y }) => y === 0 && Math.abs(x) <= 1);
life.setCells(mask);
const rng = life.read().randomState;
life.advance();
assert.equal(life.read().tick, 1);
assert.equal(life.read().counts.living, 3);
assert.deepEqual(life.read().cells.filter(cell => cell.living).map(cell => [cell.x, cell.y]), [[0, -1], [0, 0], [0, 1]]);
life.advance();
assert.deepEqual(life.read().cells.map(cell => cell.living), mask);
assert.equal(life.read().density, 3 / 25);
assert.deepEqual(life.read().randomState, rng);
life.setCells(Array(25).fill(false));
life.advance(3);
assert.equal(life.read().tick, 5);
assert.equal(life.read().counts.living, 0);
assert.equal(life.read().done, false);
