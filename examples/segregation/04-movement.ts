import assert from "node:assert/strict";
import { create } from "../../models/segregation/model.ts";
const m = create({width:5,height:5,similarWanted:100});
m.setResidents([{x:0,y:0,group:"blue"},{x:1,y:0,group:"orange"},{x:-1,y:0,group:"orange"}]);
const before=m.read();
m.advance();
const after=m.read();
assert.equal(after.tick,1);
assert.deepEqual(after.residents.map(r=>[r.id,r.group]),before.residents.map(r=>[r.id,r.group]));
assert.equal(new Set(after.residents.map(r=>`${r.x},${r.y}`)).size,3);
assert.ok(after.residents.every(r=>Number.isInteger(r.x)&&Number.isInteger(r.y)&&Math.abs(r.x)<=2&&Math.abs(r.y)<=2));
assert.equal(after.history.length,2);
assert.equal(after.history.at(-1)!.tick,1);
