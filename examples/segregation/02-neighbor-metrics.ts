import assert from "node:assert/strict";
import { create } from "../../experiments/segregation/model.ts";
const m = create({width: 5, height: 5, similarWanted: 50});
m.setResidents([{x:0,y:0,group:"blue"},{x:1,y:0,group:"blue"},{x:2,y:0,group:"orange"}]);
const s = m.read();
assert.equal(s.counts.population, 3);
assert.equal(s.counts.unhappy, 1);
assert.equal(s.percentSimilar, 50);
assert.equal(s.percentUnhappy, 100 / 3);
assert.deepEqual(s.residents.map(r => [r.similarNearby,r.otherNearby,r.happy]), [[1,0,true],[1,1,true],[0,1,false]]);
