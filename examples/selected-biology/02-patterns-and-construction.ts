import assert from "node:assert/strict";
import { create as fur } from "../../experiments/fur/model.ts";
import { create as honeycomb } from "../../experiments/honeycomb/model.ts";

const skin = fur({ seed: 1, initialDensity: 0 });
assert.equal(skin.read().cells.length, 61 * 61);
assert.equal(skin.read().whiteCount, 0);
skin.advance(3);
assert.equal(skin.read().tick, 3);
assert.equal(skin.read().whiteCount, 0);
skin.setParameters({ initialDensity: 100 });
skin.restart();
assert.equal(skin.read().tick, 0);
assert.equal(skin.read().whiteCount, 61 * 61);
skin.setParameters({ ratio: 0 });
skin.advance();
assert.equal(skin.read().whiteCount, 61 * 61);
assert.throws(() => fur({ innerRadiusX: 6, innerRadiusY: 6, outerRadiusX: 3, outerRadiusY: 3 }), RangeError);

const hive = honeycomb({ seed: 3, numBees: 10 });
assert.equal(hive.read().agents.length, 10);
hive.advance();
assert.equal(hive.read().tick, 1);
assert.ok(Math.abs(hive.read().chemicalTotal - 18) < 1e-9);
hive.advance(9);
assert.ok(Math.abs(hive.read().chemicalTotal - 198) < 1e-8);
hive.advance();
assert.ok(Math.abs(hive.read().chemicalTotal - 196.2) < 1e-8);
hive.hideBees();
assert.ok(hive.read().agents.every(agent => agent.hidden));
hive.showBees();
assert.ok(hive.read().agents.every(agent => !agent.hidden));
