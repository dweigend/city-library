import assert from "node:assert/strict";
import { geometry, type PlanarPolygon } from "city-library";

const shape: PlanarPolygon = { type: "Polygon", coordinates: [[[0, 0], [4, 0], [4, 2], [0, 2], [0, 0]]] };
const before = structuredClone(shape);
const split = geometry.split({ shape, point: { x: 2, y: 0 }, direction: { x: 0, y: 1 }, minimumArea: 3 });
assert.equal(split.status, "ok");
assert.equal(split.parts.length, 2);
assert.deepEqual(split.parts.map(part => geometry.area({ shape: part })).sort((a, b) => a - b), [4, 4]);
assert.equal(split.parts.reduce((area, part) => area + geometry.area({ shape: part }), 0), 8);
assert.notEqual(split.parts[0], shape);
assert.deepEqual(shape, before);
const narrow = geometry.split({ shape, point: { x: 0.5, y: 0 }, direction: { x: 0, y: 1 }, minimumArea: 2 });
assert.equal(narrow.status, "unchanged");
assert.deepEqual(narrow.parts, [before]);
assert.notEqual(narrow.parts[0], shape);
assert.ok(narrow.diagnostics.length > 0);
const outside = geometry.split({ shape, point: { x: 8, y: 0 }, direction: { x: 0, y: 1 } });
assert.equal(outside.status, "unchanged");
assert.deepEqual(outside.parts, [before]);
const concave: PlanarPolygon = { type: "Polygon", coordinates: [[[0, 0], [3, 0], [1, 1], [0, 3], [0, 0]]] };
const unsupported = geometry.split({ shape: concave, point: { x: 1, y: 0 }, direction: { x: 0, y: 1 } });
assert.equal(unsupported.status, "unsupported");
assert.deepEqual(unsupported.parts, [concave]);
const holed: PlanarPolygon = { type: "Polygon", coordinates: [before.coordinates[0]!, [[1, 0.5], [2, 0.5], [2, 1.5], [1, 1.5], [1, 0.5]]] };
const holeResult = geometry.split({ shape: holed, point: { x: 2, y: 0 }, direction: { x: 0, y: 1 } });
assert.equal(holeResult.status, "unsupported");
assert.equal(holeResult.parts.reduce((area, part) => area + geometry.area({ shape: part }), 0), 7);
assert.throws(() => geometry.split({ shape, point: { x: 2, y: 0 }, direction: { x: 0, y: 0 } }), RangeError);
assert.deepEqual(shape, before);
