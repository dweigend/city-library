import assert from "node:assert/strict";
import { create as births } from "../../experiments/simple-birth-rates/model.ts";
import { create as daisies } from "../../experiments/daisyworld/model.ts";
const population = births({ carryingCapacity: 1, redFertility: 0, blueFertility: 0, seed: 7 });
assert.equal(population.read().blueCount, 1);
assert.equal(population.read().redCount, 0);
population.advance(3);
assert.equal(population.read().tick, 3);
assert.equal(population.read().blueCount, 1);
const climate = daisies({ startBlacks: 0, startWhites: 0, solarLuminosity: 0.8, scenario: "maintain current luminosity" });
const heating = 72 * Math.log((1 - 0.4) * 0.8) + 80;
assert.ok(Math.abs(climate.read().globalTemperature - heating / 2) < 1e-10);
climate.advance();
assert.ok(Math.abs(climate.read().globalTemperature - heating * 0.75) < 1e-10);
assert.equal(climate.read().tick, 1);
climate.paint(0, 0, "add black");
assert.equal(climate.read().blackCount, 1);
climate.removeAllDaisies();
assert.equal(climate.read().blackCount, 0);
assert.equal(climate.read().tick, 1);
console.log("Birth initialization, generation accounting and thermal recurrence verified.");
