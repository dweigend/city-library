import assert from "node:assert/strict";
import { create } from "../../models/hex-cell-aggregation/model.ts";
const m = create({ width: 9, height: 9, seed: 3 });
assert.equal(m.read().cells.filter(c => c.alive).length, 1);
assert.equal(m.read().cells.filter(c => !c.alive && c.liveNeighborCount === 1).length, 6);
m.advance(10);
assert.equal(m.read().tick, 10);
assert.equal(m.read().cells.filter(c => c.alive).length, 11);
m.readSwitches([]);
const before = m.read();
m.advance(50);
assert.equal(m.read().tick, before.tick);
assert.deepEqual(m.read().cells, before.cells);
assert.equal(m.read().done, true);
