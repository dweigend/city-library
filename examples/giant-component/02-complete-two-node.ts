import assert from "node:assert/strict";
import { create } from "../../experiments/giant-component/model.ts";
const model=create({numberOfNodes:2});
model.advance(100);
const state=model.read();
assert.equal(state.tick,1);
assert.equal(state.edgeCount,1);
assert.equal(state.giantSize,2);
assert.equal(state.giantFraction,1);
assert.equal(state.meanDegree,1);
assert.equal(state.done,true);
assert.equal(state.stopReason,"complete");
assert.equal(state.history.length,2);
model.advance(100);
assert.deepEqual(model.read(),state);
