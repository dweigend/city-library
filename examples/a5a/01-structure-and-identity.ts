import assert from "node:assert/strict";
import { Graph } from "city-library";

const graph = Graph.add<{ label: string }>();
const alice = { label: "Alice" };
const bob = { label: "Bob" };
const carol = { label: "Carol" };
assert.equal(graph.parallel, false);
assert.equal(graph.selfLoops, false);
assert.equal(graph.nodes.add(alice), alice);
assert.equal(graph.nodes.add(bob), bob);
assert.equal(graph.nodes.add(alice), alice);
assert.equal(graph.nodes.size, 2);
assert.deepEqual(Array.from(graph.nodes), [alice, bob]);
assert.equal(graph.hasNode({ label: "Alice" }), false);
assert.throws(() => graph.edges.add({ from: bob, to: carol }));
assert.equal(graph.nodes.size, 2);
assert.equal(graph.edges.size, 0);

const edge = graph.edges.add({ from: alice, to: bob });
assert.equal(edge.from, alice);
assert.equal(edge.to, bob);
assert.equal(edge.graph, graph);
assert.equal(edge.alive, true);
assert.equal(edge.directed, false);
assert.equal(edge.key, undefined);
assert.equal(edge.path, undefined);
assert.equal(typeof edge.id, "string");
assert.ok(edge.id.length > 0);
assert.equal(graph.edges.add({ from: bob, to: alice }), edge);
assert.equal(graph.hasEdge(bob, alice), true);
assert.equal(graph.edges.has(edge), true);
assert.deepEqual(Array.from(graph.edges), [edge]);
const capturedNeighbors = graph.neighbors(bob);
assert.deepEqual(capturedNeighbors, [alice]);
assert.ok(Object.isFrozen(capturedNeighbors));
graph.nodes.add(carol);
graph.edges.add({ from: bob, to: carol });
assert.deepEqual(capturedNeighbors, [alice]);
assert.deepEqual(graph.neighbors(bob), [alice, carol]);
assert.deepEqual(graph.edges.between(carol, alice), []);
assert.equal(Reflect.set(edge, "from", carol), false);
assert.equal(Reflect.set(graph, "nodes", new Set()), false);
console.log("graph-structure: canonical object nodes, explicit endpoints and stable observation snapshots");
